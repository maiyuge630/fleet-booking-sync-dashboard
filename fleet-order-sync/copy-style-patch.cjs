function copy(text){for(const [from,to] of replacements)text=text.split(from).join(to);return text;}
function patchCopyStyle(source){
 let result=source;
 for(const [name,endAnchor,cspKey] of [['HTML','var LOGIN_HTML = ','dashboard'],['LOGIN_HTML','var SEED = ','login'],['ORDER_SYNC_HTML','var ORDER_SYNC_CSP = ',null]]){
  const start=result.indexOf('var '+name+' = '),end=result.indexOf(endAnchor,start);
  if(start<0||end<0)throw Error('Copy HTML anchor missing: '+name);
  const before=vm.runInNewContext(result.slice(start,end)+';'+name);
  let after=copy(before);
  // Availability labels are contextual: do not replace network/service availability.
  after=after.replace(/(['"])不可用\1/g,"'不可预订'").replace(/(['"])可用\1/g,"'可预订'")
   .replace(/>不可用</g,'>不可预订<').replace(/>可用</g,'>可预订<')
   .replaceAll(' 艘可用',' 艘可预订').replaceAll(' 艘不可用',' 艘不可预订')
   .replaceAll(' · 不可用',' · 不可预订').replaceAll('连续不可用日期','连续不可预订日期')
   .replaceAll(' 不可用 ·',' 不可预订 ·').replaceAll(' 不可用，',' 不可预订，')
   .replaceAll("'手锁'","'手动'").replaceAll("'撞'","'重叠'").replaceAll("'订'","'预订'")
   .replaceAll("?'可用':", "?'可预订':");
  const script=after.match(/<script>([\s\S]*?)<\/script>/)?.[1];
  if(!script)throw Error('Copy script missing: '+name);
  new vm.Script(script);
  result=result.slice(0,start)+'var '+name+' = '+JSON.stringify(after)+';\n'+result.slice(end);
  const scriptHash=createHash('sha256').update(script).digest('base64');
  if(cspKey){
   const pattern=new RegExp('(\"'+cspKey+'\":\\s*\"default-src \'none\'; script-src \'sha256-)[^\']+(\';)');
   if(result.match(new RegExp(pattern.source,'g'))?.length!==1)throw Error('Copy CSP anchor missing: '+name);
   result=result.replace(pattern,(_,a,b)=>a+scriptHash+b);
  }else{
   const pattern=/(var ORDER_SYNC_CSP = "default-src 'none'; script-src 'sha256-)[^']+(';)/;
   if(result.match(new RegExp(pattern.source,'g'))?.length!==1)throw Error('Copy sync CSP anchor missing');
   result=result.replace(pattern,(_,a,b)=>a+scriptHash+b);
  }
 }
 return result;
}
